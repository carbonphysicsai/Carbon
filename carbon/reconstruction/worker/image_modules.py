"""The carbon files the worker image really needs: the container's own imports, not the whole package.

OWNER "Narrow it first" (after OWNER-IMAGE-TIE-QUICK-FIX-NOW-FULL-LATER-01): any `carbon/` edit used to move the worker
image id, and with it every pack, the derived GPU images, their stage-2 record and receipts. The container's staged
programs run host-staged, digest-bound copies of their modules (they write empty `__init__.py` files into
`work/carbon/**` and copy `STAGED_MODULES` in, shadowing the installed package), so what the image's own `carbon` is used
for is the entrypoint process: `python -I -m carbon.reconstruction.worker.entrypoint`. Host-only code (receiver, door,
MCP, validator setup, host-side scoring, Launchpad ...) is never imported there, so it no longer needs to be baked in or
to move the image id.

The set is GENERATED and then checked, never hand-edited:

    list = module-level import closure of the entrypoint            (AST; nothing is imported)
         + one lazy level: every module a closure module imports inside a function, with its own module-level closure
         + the committed runtime-trace allow-list `worker_image_trace.txt` (modules a box trace of every job kind found)
         + the package data of every package that has a module in the list (pyproject package-data)
         + this tool, its generated files and the build inputs file themselves.

Files it writes (all under version control, all inputs):
    carbon/reconstruction/worker/worker_image_files.txt        the carbon files baked into the image
    carbon/reconstruction/worker/build_inputs.txt              the build inputs (the digest every image identity is scoped to)
    .devcontainer/Dockerfile.reconstruction-worker.dockerignore the BuildKit allow-list that makes `COPY carbon` copy only those

    python carbon/reconstruction/worker/image_modules.py generate [REPO]   # rewrite the three files
    python carbon/reconstruction/worker/image_modules.py check [REPO]      # exit 1 when they are not what the code gives
    python -I -m carbon.reconstruction.worker.image_modules smoke          # IN the image: import every listed module and
                                                                           # refuse any `.py` the list does not name
    python carbon/reconstruction/worker/image_modules.py trace-check [REPO] < modules.txt
                                                                           # a container's traced imports not in the list

A module a container really needs but the closure missed fails CLOSED: its file is absent from the image, so the first use is an
ImportError (a worker failure), never a different grade. Standard library only.
"""

from __future__ import annotations

import ast
import importlib
import re
import sys
from pathlib import Path

import tomllib

ENTRYPOINT = "carbon.reconstruction.worker.entrypoint"
WORKER_DIR = "carbon/reconstruction/worker"
FILES_FILE = WORKER_DIR + "/worker_image_files.txt"
TRACE_FILE = WORKER_DIR + "/worker_image_trace.txt"
INPUTS_FILE = WORKER_DIR + "/build_inputs.txt"
DOCKERIGNORE = ".devcontainer/Dockerfile.reconstruction-worker.dockerignore"
TOOL_FILES = (
    WORKER_DIR + "/image_modules.py",
    WORKER_DIR + "/build_inputs.py",
    FILES_FILE,
    TRACE_FILE,
    INPUTS_FILE,
)
#: Build inputs that are not carbon files (everything a worker Dockerfile COPYs besides `carbon`, and the Dockerfiles).
OTHER_INPUTS = (
    "pyproject.toml",
    "uv.lock",
    "README.md",
    ".devcontainer/Dockerfile.reconstruction-worker",
    DOCKERIGNORE,
    ".devcontainer/worker-native-mesh.lock",
    ".devcontainer/install-worker-native-mesh.sh",
    ".devcontainer/accelerators",
    ".devcontainer/torch",
)
#: The repository `.dockerignore` lines this Dockerfile's own ignore file must repeat (BuildKit reads the Dockerfile's
#: `<name>.dockerignore` INSTEAD of the root `.dockerignore`).
BASE_IGNORE = (
    ".git",
    ".venv",
    ".pytest_cache",
    ".ruff_cache",
    "**/__pycache__",
    "build",
    "dist",
    "*.egg-info",
    ".carbon-artifacts",
)
HEADER = "# GENERATED by carbon/reconstruction/worker/image_modules.py (`generate`); do not edit by hand.\n"


def _skip(path: Path) -> bool:
    return "node_modules" in path.parts or "__pycache__" in path.parts


def module_index(repo) -> dict:
    """{module name: repo-relative file} for every `.py` under carbon/."""
    repo = Path(repo)
    index = {}
    for path in sorted((repo / "carbon").rglob("*.py")):
        if _skip(path.relative_to(repo)):
            continue
        rel = path.relative_to(repo).as_posix()
        name = rel[:-3].replace("/", ".")
        index[name.removesuffix(".__init__")] = rel
    return index


def _resolved(index, module, node) -> set:
    path = index[module]
    package = module if path.endswith("__init__.py") else module.rpartition(".")[0]
    names = set()
    if isinstance(node, ast.Import):
        names.update(alias.name for alias in node.names)
    else:
        base = node.module or ""
        if node.level:
            parts = package.split(".") if package else []
            if node.level > 1:
                parts = parts[: len(parts) - (node.level - 1)]
            base = ".".join([*parts, *([node.module] if node.module else [])])
        names.add(base)
        names.update(base + "." + alias.name for alias in node.names)
    return {name for name in names if name in index}


def split_imports(repo, index, module):
    """(module-level imports, function-level imports) of one module, restricted to carbon modules.

    A string literal that is exactly a carbon module name (a `python -m` target, an `import_module` literal, a staged
    module list) counts as a function-level reference: the container reaches it by name, not by an import statement.
    """
    tree = ast.parse((Path(repo) / index[module]).read_text(encoding="utf-8"))
    eager, lazy = set(), set()
    for node in ast.walk(tree):
        if (
            isinstance(node, ast.Constant)
            and isinstance(node.value, str)
            and node.value in index
        ):
            lazy.add(node.value)

    def walk(nodes, inside_function):
        for node in nodes:
            if isinstance(node, (ast.Import, ast.ImportFrom)):
                (lazy if inside_function else eager).update(
                    _resolved(index, module, node)
                )
            elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.Lambda)):
                walk(ast.iter_child_nodes(node), True)
            else:
                walk(ast.iter_child_nodes(node), inside_function)

    walk(tree.body, False)
    return eager, lazy


def _with_parents(module):
    parts = module.split(".")
    return {".".join(parts[:i]) for i in range(1, len(parts) + 1)}


def eager_closure(repo, index, roots, lazies=None) -> set:
    """The module-level import closure of ``roots`` (parent packages included); ``lazies`` collects each module's
    function-level imports."""
    seen, stack = set(), list(roots)
    while stack:
        module = stack.pop()
        if module in seen or module not in index:
            continue
        seen.add(module)
        stack.extend(_with_parents(module))
        eager, lazy = split_imports(repo, index, module)
        stack.extend(eager)
        if lazies is not None:
            lazies[module] = lazy
    return seen


def trace_modules(repo) -> list:
    path = Path(repo) / TRACE_FILE
    if not path.is_file():
        return []
    return [
        line.strip()
        for line in path.read_text(encoding="utf-8").splitlines()
        if line.strip() and not line.lstrip().startswith("#")
    ]


def closure(repo) -> set:
    """The modules the image carries (see the module docstring)."""
    index = module_index(repo)
    lazies: dict = {}
    roots = [ENTRYPOINT, *trace_modules(repo)]
    base = eager_closure(repo, index, roots, lazies)
    one_level = {name for names in lazies.values() for name in names} - base
    return base | eager_closure(repo, index, one_level)


#: A module that reads files next to itself names its own location.
DATA_MARKERS = ("__file__", "importlib.resources", "pkgutil.get_data")


def _reads_beside_itself(repo, index, module) -> bool:
    text = (Path(repo) / index[module]).read_text(encoding="utf-8")
    return any(marker in text for marker in DATA_MARKERS)


def package_data_files(repo, modules) -> set:
    """pyproject package-data files of every package that has a module in ``modules`` which reads files beside itself
    (`__file__`, importlib.resources): the wheel only ever carried package data, so this is the most the image can need;
    a data-free package contributes none. Also every `.py` a listed module globs from its own directory
    (`Path(__file__).parent.glob("*.py")`: the vendored lab's source hash covers the whole directory).
    """
    repo = Path(repo)
    index = module_index(repo)
    project = tomllib.loads((repo / "pyproject.toml").read_text(encoding="utf-8"))
    data = project["tool"]["setuptools"].get("package-data", {})
    reading = {
        module.rpartition(".")[0]
        if not index[module].endswith("__init__.py")
        else module
        for module in modules
        if _reads_beside_itself(repo, index, module)
    }
    found = set()
    for module in modules:
        text = (repo / index[module]).read_text(encoding="utf-8")
        if '.parent.glob("*.py")' in text:
            folder = (repo / index[module]).parent
            found.update(
                path.relative_to(repo).as_posix()
                for path in folder.glob("*.py")
                if not _skip(path.relative_to(repo))
            )
    for package, patterns in data.items():
        if not package.startswith("carbon") or package not in reading:
            continue
        folder = repo / Path(*package.split("."))
        for pattern in patterns:
            for path in sorted(folder.glob(pattern)):
                if path.is_file() and not _skip(path.relative_to(repo)):
                    found.add(path.relative_to(repo).as_posix())
    return found


DATA_MARKER = "# --- files the image reads but never imports ---"


def files_by_kind(repo):
    """(importable module files, files read but not imported), each sorted and repo-relative."""
    index = module_index(repo)
    modules = closure(repo)
    importable = {index[name] for name in modules}
    other = (package_data_files(repo, modules) | set(TOOL_FILES)) - importable
    return sorted(importable), sorted(other)


def files(repo) -> list:
    """The sorted repo-relative carbon files baked into the image."""
    importable, other = files_by_kind(repo)
    return sorted([*importable, *other])


def render_files(repo) -> str:
    importable, other = files_by_kind(repo)
    return (
        HEADER
        + "".join(path + "\n" for path in importable)
        + DATA_MARKER
        + "\n"
        + "".join(path + "\n" for path in other)
    )


def render_inputs(repo) -> str:
    return (
        "# The worker image's build inputs: every path a worker Dockerfile COPYs, the Dockerfiles, and the derived images'\n"
        "# input directories. The carbon files are the image's own imports (carbon/reconstruction/worker/image_modules.py),\n"
        "# GENERATED: `python carbon/reconstruction/worker/image_modules.py generate`; a test fails when this file differs.\n"
        "# One path per line, relative to the repository root. `source_tree_digest` of a worker-image-build.v2 record is the\n"
        "# digest of the git tree listing (modes and blob ids) of these paths at HEAD.\n"
        + "".join(path + "\n" for path in OTHER_INPUTS[:3])
        + "".join(path + "\n" for path in files(repo))
        + "".join(path + "\n" for path in OTHER_INPUTS[3:])
    )


def render_dockerignore(repo) -> str:
    return (
        HEADER
        + "# BuildKit reads this INSTEAD of the root .dockerignore for this Dockerfile: the base lines are repeated, then only\n"
        + "# the carbon files the image needs are let through `COPY carbon ./carbon`.\n"
        + "".join(line + "\n" for line in BASE_IGNORE)
        + "carbon/**\n"
        + "".join(
            "!" + path + "\n" for path in files(repo) if path.startswith("carbon/")
        )
    )


def generated(repo) -> dict:
    return {
        FILES_FILE: render_files(repo),
        INPUTS_FILE: render_inputs(repo),
        DOCKERIGNORE: render_dockerignore(repo),
    }


def write(repo) -> None:
    for relative, text in generated(repo).items():
        target = Path(repo) / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(text.encode("utf-8"))


def stale(repo) -> list:
    """The generated files whose committed bytes differ from what the code gives."""
    out = []
    for relative, text in generated(repo).items():
        path = Path(repo) / relative
        if not path.is_file() or path.read_bytes() != text.encode("utf-8"):
            out.append(relative)
    return out


def listed_files(repo) -> list:
    """The carbon files named by the committed FILES_FILE (what the image carries)."""
    return [
        line.strip()
        for line in (Path(repo) / FILES_FILE).read_text(encoding="utf-8").splitlines()
        if line.strip() and not line.startswith("#")
    ]


def listed_modules(repo) -> list:
    """The modules the committed list says the image imports (the part before DATA_MARKER)."""
    names = []
    for line in (Path(repo) / FILES_FILE).read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line == DATA_MARKER:
            break
        if line and not line.startswith("#") and line.endswith(".py"):
            names.append(line[:-3].replace("/", ".").removesuffix(".__init__"))
    return names


def docker_survivors(repo, ignore_text, candidates) -> set:
    """The ``candidates`` a BuildKit `.dockerignore` lets into the context (last matching pattern wins; a pattern also
    matches everything under a matched directory; `**` crosses `/`, `*` and `?` do not). Used by the tests.
    """
    patterns = []
    for line in ignore_text.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        negated = line.startswith("!")
        patterns.append((negated, line[1:] if negated else line))

    def matches(pattern, path):
        out, i = "", 0
        while i < len(pattern):
            char = pattern[i]
            if pattern.startswith("**/", i):
                out += "(?:.*/)?"
                i += 3
            elif pattern.startswith("**", i):
                out += ".*"
                i += 2
            elif char == "*":
                out += "[^/]*"
                i += 1
            elif char == "?":
                out += "[^/]"
                i += 1
            else:
                out += re.escape(char)
                i += 1
        pattern_re = re.compile("^" + out + "(?:/.*)?$")
        return pattern_re.match(path) is not None

    survivors = set()
    for path in candidates:
        excluded = False
        for negated, pattern in patterns:
            if matches(pattern, path):
                excluded = not negated
        if not excluded:
            survivors.add(path)
    return survivors


def smoke() -> int:
    """IN the image: import every listed module (a missing one fails the BUILD) and refuse any carbon `.py` the list does
    not name (the image was built with a context the allow-list did not filter, e.g. a legacy builder).
    """
    root = Path(__import__("carbon").__file__).resolve().parent.parent
    names = []
    listed = set()
    importing = True
    for line in (root / FILES_FILE).read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line == DATA_MARKER:
            importing = False
        if line and not line.startswith("#") and line.endswith(".py"):
            listed.add(line)
            if importing:
                names.append(line[:-3].replace("/", ".").removesuffix(".__init__"))
    failures = []
    for name in sorted(names):
        try:
            importlib.import_module(name)
        except Exception as exc:  # noqa: BLE001 - report every failure, then fail
            failures.append(f"{name}: {type(exc).__name__}: {exc}"[:240])
    present = {
        path.relative_to(root).as_posix()
        for path in (root / "carbon").rglob("*.py")
        if not _skip(path.relative_to(root))
    }
    extra = sorted(present - listed)
    if failures or extra:
        for line in failures:
            print("import failed:", line, file=sys.stderr)
        for path in extra:
            print("not in the list:", path, file=sys.stderr)
        return 1
    print(f"worker image modules: {len(names)} imported, none outside the list")
    return 0


def trace_check(repo, names) -> list:
    """The `carbon.*` modules in ``names`` (a trace of what a container really imported, one module per name) that the
    committed list does not carry. A trace harness feeds this; every name it returns must be added to
    `worker_image_trace.txt` (then `generate`) or be proven not to run in the container.
    """
    listed = set(listed_modules(repo))
    return sorted(
        {
            name
            for name in names
            if (name == "carbon" or name.startswith("carbon.")) and name not in listed
        }
    )


def main(argv=None) -> int:
    args = list(sys.argv[1:] if argv is None else argv)
    if args[:1] == ["trace-check"] and len(args) in (1, 2):
        repo = Path(args[1]) if len(args) == 2 else Path(__file__).resolve().parents[3]
        extra = trace_check(repo, (line.strip() for line in sys.stdin))
        print("\n".join(extra))
        return 1 if extra else 0
    repo = Path(args[1]) if len(args) == 2 else Path(__file__).resolve().parents[3]
    if args[:1] == ["generate"] and len(args) in (1, 2):
        write(repo)
        print("\n".join(sorted(generated(repo))))
        return 0
    if args[:1] == ["check"] and len(args) in (1, 2):
        out = stale(repo)
        print("\n".join(out))
        return 1 if out else 0
    if args == ["smoke"]:
        return smoke()
    print(
        "usage: image_modules.py generate [REPO] | check [REPO] | smoke | trace-check [REPO] < modules",
        file=sys.stderr,
    )
    return 2


if __name__ == "__main__":
    sys.exit(main())
