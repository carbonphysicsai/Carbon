def test_run_basis_pins_sources_tools_and_all_stable_outputs():
    run = read("tool-run.json")
    assert run["status"] == "DRAFT_GENERATORS_EXERCISED_NOT_STAGE_ACCEPTANCE"
    assert run["solver_runs"] == 0 and run["spend_authorized"] is False
    assert run["protected_material_access"] is False
    assert run["authority_main"] == "94b193525f5d55eb20168ebbdbcf43ddf33653f1"
    # Provenance, never freshness: outputs match their recorded digests, inputs match
    # the tree AT authority_main where git history allows, and the record is complete.
    report = provenance.check(ROOT, RELATIVE + "tool-run.json")
    assert report["provenance_problems"] == []
    assert report["freshness"] in (provenance.CURRENT, provenance.STALE_TOOLS)
    for digest in [*run["inputs_and_tools"].values(), *run["outputs"].values()]:
        assert len(digest) == 64 and set(digest) <= set("0123456789abcdef")
    assert len(run["candidate_views"]) == 2
    for row in run["candidate_views"]:
        assert row["source_extract_count"] == 0
        assert row["field_count"] == 38
        assert row["read_artifacts"] == row["configured_artifacts"] == 4
        assert row["verified_exits"] == 0
        assert row["tested_challenge_claim"] is False


def test_inputs_match_the_tools_at_authority_main_not_at_head():
    report = provenance.check(ROOT, RELATIVE + "tool-run.json")
    if not report["history_checked"]:
        pytest.skip(
            "authority_main is not in this clone's git history (a shallow clone): "
            "inputs cannot be compared with the bytes at authority_main here"
        )
    # With history present every tool and source matched its bytes AT authority_main
    # (a mismatch would be a provenance problem), so this is not a vacuous pass.
    assert report["provenance_problems"] == []


# -- provenance fails on tampering and incomplete records; freshness never fails -------------------
def _git(root, *args):
    subprocess.run(
        ["git", "-c", "user.email=t@t", "-c", "user.name=t", *args],
        cwd=root,
        check=True,
        capture_output=True,
    )


def _pack(tmp_path):
    """A tiny committed pack: one tool and one source at authority_main, one output."""
    (tmp_path / "pack").mkdir()
    (tmp_path / "tool.py").write_text("TOOL = 1\n", encoding="utf-8")
    (tmp_path / "source.md").write_text("source\n", encoding="utf-8")
    _git(tmp_path, "init", "-q")
    _git(tmp_path, "add", "-A")
    _git(tmp_path, "commit", "-q", "-m", "authority")
    authority = subprocess.run(
        ["git", "rev-parse", "HEAD"],
        cwd=tmp_path,
        capture_output=True,
        text=True,
        check=True,
    ).stdout.strip()
    (tmp_path / "pack/out.md").write_text("output\n", encoding="utf-8")
    (tmp_path / "pack/in.json").write_text("{}\n", encoding="utf-8")

    def sha(relative):
        return provenance.digest((tmp_path / relative).read_bytes())

    run = {
        "schema": "carbon.test.tool-run.v1",
        "ticket": "T-1",
        "status": "DRAFT",
        "authority_main": authority,
        "recorded_at": "2026-10-10T00:00:00Z",
        "inputs_and_tools": {
            "tool.py": sha("tool.py"),
            "source.md": sha("source.md"),
            "pack/in.json": sha("pack/in.json"),
        },
        "outputs": {"pack/out.md": sha("pack/out.md")},
    }
    (tmp_path / "pack/tool-run.json").write_text(json.dumps(run), encoding="utf-8")
    return run


def _check(tmp_path):
    return provenance.check(tmp_path, "pack/tool-run.json")


def test_an_intact_pack_is_consistent_and_current(tmp_path):
    _pack(tmp_path)
    report = _check(tmp_path)
    assert report["provenance_problems"] == [] and report["history_checked"] is True
    assert report["freshness"] == provenance.CURRENT and report["changed_paths"] == []


def test_a_later_change_to_a_tool_is_reported_stale_not_failed(tmp_path):
    _pack(tmp_path)
    (tmp_path / "tool.py").write_text("TOOL = 2\n", encoding="utf-8")
    report = _check(tmp_path)
    assert report["provenance_problems"] == []
    assert report["freshness"] == provenance.STALE_TOOLS
    assert report["changed_paths"] == ["tool.py"]


def test_a_tampered_output_fails_provenance(tmp_path):
    _pack(tmp_path)
    (tmp_path / "pack/out.md").write_text("tampered\n", encoding="utf-8")
    problems = _check(tmp_path)["provenance_problems"]
    assert problems == ["output digest differs from committed bytes: pack/out.md"]


def test_a_missing_output_fails_provenance(tmp_path):
    _pack(tmp_path)
    (tmp_path / "pack/out.md").unlink()
    assert "output missing: pack/out.md" in _check(tmp_path)["provenance_problems"]


def test_a_bad_recorded_digest_fails_provenance(tmp_path):
    run = _pack(tmp_path)
    run["inputs_and_tools"]["tool.py"] = "not-a-digest"
    run["outputs"]["pack/out.md"] = "ab" * 31
    (tmp_path / "pack/tool-run.json").write_text(json.dumps(run), encoding="utf-8")
    problems = _check(tmp_path)["provenance_problems"]
    assert "input digest malformed: tool.py" in problems
    assert "output digest malformed: pack/out.md" in problems


def test_an_input_digest_that_was_never_the_tool_at_authority_main_fails(tmp_path):
    run = _pack(tmp_path)
    run["inputs_and_tools"]["tool.py"] = provenance.digest(b"TOOL = 99\n")
    (tmp_path / "pack/tool-run.json").write_text(json.dumps(run), encoding="utf-8")
    problems = _check(tmp_path)["provenance_problems"]
    assert "input digest differs at authority_main: tool.py" in problems


def test_a_pack_input_that_changed_fails_because_it_is_part_of_the_record(tmp_path):
    _pack(tmp_path)
    (tmp_path / "pack/in.json").write_text('{"changed": true}\n', encoding="utf-8")
    assert "pack input differs from committed bytes: pack/in.json" in (
        _check(tmp_path)["provenance_problems"]
    )


@pytest.mark.parametrize(
    "key", ["schema", "ticket", "status", "authority_main", "recorded_at", "outputs"]
)
def test_an_incomplete_run_record_fails_provenance(tmp_path, key):
    run = _pack(tmp_path)
    del run[key]
    (tmp_path / "pack/tool-run.json").write_text(json.dumps(run), encoding="utf-8")
    problems = _check(tmp_path)["provenance_problems"]
    assert any(key in problem for problem in problems), problems


def test_a_malformed_authority_main_fails_provenance(tmp_path):
    run = _pack(tmp_path)
    run["authority_main"] = "main"
    (tmp_path / "pack/tool-run.json").write_text(json.dumps(run), encoding="utf-8")
    assert "authority_main is not a 40-hex commit" in (
        _check(tmp_path)["provenance_problems"]
    )


def test_an_unreadable_run_record_fails_provenance(tmp_path):
    assert _check(tmp_path)["provenance_problems"] == ["run record unreadable"]


def test_the_pack_command_reports_freshness_and_fails_only_on_provenance(
    tmp_path, capsys
):
    from carbon.challenge_pipeline.onboarding.__main__ import main

    _pack(tmp_path)
    (tmp_path / "tool.py").write_text("TOOL = 2\n", encoding="utf-8")
    assert main(["--root", str(tmp_path), "pack", "--run", "pack/tool-run.json"]) == 0
    assert "freshness: STALE_TOOLS" in capsys.readouterr().out
    (tmp_path / "pack/out.md").write_text("tampered\n", encoding="utf-8")
    code = main(["--root", str(tmp_path), "pack", "--run", "pack/tool-run.json"])
    assert code == 1 and "PROVENANCE PROBLEMS" in capsys.readouterr().out
