from carbon.challenge_pipeline.onboarding import provenance, status

ROOT = Path(__file__).resolve().parents[2]
RELATIVE = "docs/development/challenge_pipeline/open-benchmark-onboarding/"
FOLDER = ROOT / RELATIVE
TOKENS = ("backward-facing-step", "metagrating-3d")


def read(name):
    return json.loads((FOLDER / name).read_text(encoding="utf-8"))


@pytest.mark.parametrize("token", TOKENS)
def test_four_outputs_are_the_recorded_historical_outputs(token):
    """The pack is an immutable record (invariant 10): its outputs are checked against
    the digests recorded in the run, and their structure, not against what today's
    tools would generate. A fresh run is a new, versioned pack."""
    report = provenance.check(ROOT, RELATIVE + "tool-run.json")
    assert report["provenance_problems"] == []
    packet_text = (FOLDER / (token + "-packet.md")).read_text(encoding="utf-8")
    assert packet_text.count("\n## ") == 10
    brief = read(token + "-brief.json")
    assert brief["fields"]  # the draft (38 fields) is regenerated by tools, not here
    assert read(token + "-law.json")["panel_basis"] is None
    assert read(token + "-panel.json")["cases"] == []
    status_text = (FOLDER / (token + "-status.md")).read_text(encoding="utf-8")
    assert "UNDETERMINED_WITHOUT_VERIFIED_EXIT_EVIDENCE" in status_text


